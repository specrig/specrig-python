from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from . import _yaml

FORMAT = "surface/1"
CHECKS = "checks/1"


@dataclass
class Surface:
    service: str
    publishes: set[str] = field(default_factory=set)
    consumes: set[str] = field(default_factory=set)
    serves: set[str] = field(default_factory=set)
    calls: set[str] = field(default_factory=set)
    clients: dict[str, set[str]] = field(default_factory=dict)
    settings: set[str] = field(default_factory=set)
    optional: set[str] = field(default_factory=set)
    consumers: set[str] = field(default_factory=set)

    def call(self, client: str, request: str) -> None:
        self.calls.add(request)
        self.clients.setdefault(client, set()).add(request)

    def encode(self) -> str:
        return "# Generated by `specrig surface` from the service's code.\n" + _yaml.emit(
            {
                "specrig": FORMAT,
                "service": self.service,
                "publishes": sorted(self.publishes),
                "consumes": sorted(self.consumes),
                "serves": sorted(self.serves),
                "calls": sorted(self.calls),
                "clients": {client: sorted(self.clients[client]) for client in sorted(self.clients)},
            }
        )

    def encode_checks(self) -> str:
        return (
            "# Generated by `specrig surface` from the service's code: what its boot is checked against.\n"
            + _yaml.emit(
                {
                    "specrig": CHECKS,
                    "service": self.service,
                    "settings": sorted(self.settings),
                    "optional": sorted(self.optional - self.settings),
                    "consumers": sorted(self.consumers),
                }
            )
        )


def rewrite(file: Path, body: str) -> bool:
    if file.is_file() and file.read_text(encoding="utf-8") == body:
        return False
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(body, encoding="utf-8")
    return True


@dataclass(frozen=True)
class Checks:
    settings: tuple[str, ...] = ()
    optional: tuple[str, ...] = ()
    consumers: tuple[str, ...] = ()

    @staticmethod
    def of(file: Path) -> Checks | None:
        data = _yaml.read(file)
        if data is None:
            return None
        if not isinstance(data, dict) or str(data.get("specrig", CHECKS)) != CHECKS:
            raise ValueError(f"{file} is no {CHECKS} record")

        def listed(key: str) -> tuple[str, ...]:
            return tuple(str(v) for v in data.get(key) or [])

        return Checks(listed("settings"), listed("optional"), listed("consumers"))

    def read(self) -> list[str]:
        return list(dict.fromkeys([*self.settings, *self.optional]))

    def unread(self, answered: list[str]) -> list[str]:
        return [a for a in answered if a not in self.read()]
